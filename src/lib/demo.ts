export function demoBoard(date = "2026-10-15"): Board {
  const pairings: [number, number, League, number, number, number][] = [
    [0, 1, "NBA", 19, 1.61, 2.4],
    [2, 3, "NBA", 20, 1.5, 2.65],
    [4, 5, "NBA", 22, 1.95, 1.91],
    [6, 7, "NBA", 19, 1.55, 2.5],
    [8, 9, "NFL", 20, 1.8, 2.1],
    [10, 11, "MLB", 21, 1.72, 2.25],
    [12, 13, "NHL", 19, 1.85, 2.05],
    [14, 15, "NCAAM", 18, 1.5, 2.6],
  ];
  const games = pairings.map(([h, a, league, hour, hp, ap], i): Game => ({
    id: `demo-${i + 1}`,
    league,
    start: `${date}T${String(hour).padStart(2, "0")}:30:00-04:00`,
    state: i === 2 ? "in" : "pre",
    status: i === 2 ? "Q3 · 06:42" : "Scheduled",
    statusName: i === 2 ? "STATUS_IN_PROGRESS" : "STATUS_SCHEDULED",
    period: i === 2 ? 3 : 0,
    clock: i === 2 ? "6:42" : "0:00",
    home: { ...teams[h], score: i === 2 ? 78 : 0 },
    away: { ...teams[a], score: i === 2 ? 74 : 0 },
    venue: [
      "TD Garden",
      "Paycom Center",
      "Chase Center",
      "Rocket Arena",
      "Arrowhead Stadium",
      "Dodger Stadium",
      "Amerant Bank Arena",
      "Spectrum Center",
    ][i],
    neutral: i === 7,
    season: "Illustrative season",
    seasonType: i === 7 ? 3 : 2,
    context:
      i === 7
        ? "ACC Tournament · Semifinal"
        : "Regular season · sample matchup",
    demo: true,
    quotes: [
      {
        id: `sample-book-${i}`,
        provider: "Sample sportsbook",
        kind: "sportsbook",
        homePrice: hp,
        awayPrice: ap,
        updatedAt: timestamp,
        url: "",
        note: "Illustrative price; not a current or executable quote.",
      },
      {
        id: `sample-poly-${i}`,
        provider: "Sample prediction market",
        kind: "prediction",
        homePrice: 1 / (1 / hp - 0.025),
        awayPrice: 1 / (1 - (1 / hp - 0.025)),
        updatedAt: timestamp,
        url: "",
        volume: 120400 + i * 18650,
        note: "Illustrative outcome price; not a real market.",
      },
    ],
    source: {
      name: "Sportsdesk sample dataset",
      url: "",
      fetchedAt: timestamp,
      note: "All matchups, statistics, records, player availability and prices are illustrative.",
    },
  }));
  return {
    games,
    teams: games.flatMap((g) => [
      { ...g.home, league: g.league },
      { ...g.away, league: g.league },
    ]),
    leagues: (["NBA", "NFL", "MLB", "NHL", "NCAAM"] as League[]).map(
      (league) => ({ league, season: "Illustrative season" }),
    ),
    fetchedAt: timestamp,
    mode: "demo",
    warnings: [
      "Sample desk: illustrative matchups and statistics. Switch to Live data for current research.",
    ],
  };
}
