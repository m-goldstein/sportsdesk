import { test, expect } from "@playwright/test";

test("GPT packet preview, streamed sample report, citations and export work without authentication", async ({
  page,
}) => {
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("/?mode=demo&date=2026-10-15");
  await page
    .locator(".featured-card")
    .filter({ hasText: "Celtics" })
    .getByRole("button", { name: "Research matchup" })
    .click();
  const dialog = page.getByRole("dialog", { name: "Matchup research packet" });
  await dialog.getByRole("tab", { name: "GPT analysis", exact: true }).click();
  const start = dialog.getByRole("button", { name: "View sample analysis" });
  await expect(start).toBeEnabled();
  await expect(
    dialog.locator(".gpt-coverage .pill").filter({ hasText: "Coaching" }),
  ).toBeVisible();
  await start.click();
  await expect(
    dialog.getByText("ILLUSTRATIVE REPORT · NOT GENERATED BY GPT", {
      exact: true,
    }),
  ).toBeVisible();
  await expect(
    dialog.getByRole("heading", { name: "Coach background", exact: true }),
  ).toBeVisible();
  await expect(
    dialog.getByRole("heading", {
      name: "The strongest counter-case",
      exact: true,
    }),
  ).toBeVisible();
  await expect(dialog.locator(".gpt-citations").first()).toContainText("E001");
  await dialog.locator(".gpt-evidence summary").first().click();
  await expect(
    dialog.getByRole("button", { name: "Download input packet" }),
  ).toBeVisible();
  const exported = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Export GPT analysis" }).click();
  expect((await exported).suggestedFilename()).toBe(
    "sportsdesk-gpt-demo-1.json",
  );
  await dialog.getByRole("tab", { name: "Players", exact: true }).click();
  await dialog.getByRole("tab", { name: "GPT analysis", exact: true }).click();
  await expect(
    dialog.getByRole("heading", {
      name: "The strongest counter-case",
      exact: true,
    }),
  ).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(
    await page.evaluate(
      () => document.documentElement.scrollWidth <= innerWidth,
    ),
  ).toBe(true);
  expect(errors).toEqual([]);
});
test("GPT API errors stay visible and allow retry", async ({ page }) => {
  await page.goto("/?mode=demo&date=2026-10-15");
  await page
    .locator(".featured-card")
    .filter({ hasText: "Celtics" })
    .getByRole("button", { name: "Research matchup" })
    .click();
  const dialog = page.getByRole("dialog", { name: "Matchup research packet" });
  await dialog.getByRole("tab", { name: "GPT analysis", exact: true }).click();
  await expect(
    dialog.getByRole("button", { name: "View sample analysis" }),
  ).toBeEnabled();
  await page.route("**/api/analysis", (route) =>
    route.fulfill({
      status: 429,
      contentType: "application/json",
      body: JSON.stringify({
        error: "OpenAI's rate or billing quota was reached.",
      }),
    }),
  );
  await dialog.getByRole("button", { name: "View sample analysis" }).click();
  await expect(dialog.getByRole("alert")).toContainText("quota");
  await expect(
    dialog.getByRole("button", { name: "View sample analysis" }),
  ).toBeEnabled();
});
